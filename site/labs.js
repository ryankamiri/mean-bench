export function labFor(model) {
  const id = model.developer === "other"
    ? families.find(([prefix]) => model.id.startsWith(prefix))?.[1]
    : model.developer;
  return labs[id] ?? [model.developer === "other" ? "Developer unverified" : model.developer, null];
}
